import type { Rule, Scholarship } from "./model";
const level = (...accepts: string[]): Rule => ({
  field: "level",
  label: `For ${accepts.join(" or ").toLowerCase()} students`,
  accepts,
});
const subject = (...accepts: string[]): Rule => ({
  field: "field",
  label: `Study ${accepts.join(" or ").toLowerCase()}`,
  accepts,
});
const state = (...accepts: string[]): Rule => ({
  field: "region",
  label: `Resident of ${accepts.join(" or ")}`,
  accepts,
});
const marks = (minimum: number): Rule => ({
  field: "marks",
  label: `At least ${minimum}% in your latest academic result`,
  minimum,
});
const income: Rule = {
  field: "income",
  label: "Household income up to ₹5 lakh per year",
  accepts: ["Up to ₹2.5 lakh", "₹2.5–5 lakh"],
};
const documents = [
  "Latest academic transcript",
  "Proof of enrollment",
  "Personal statement",
];
const steps = [
  "Check every eligibility requirement and confirm the current application cycle with the provider.",
  "Prepare the required documents and draft your personal statement.",
  "Complete the application on the provider’s official portal, when one is available.",
  "After submitting externally, mark your application as Applied in GRANTLY.",
];
function sample(
  id: string,
  title: string,
  provider: string,
  mark: string,
  category: string,
  amount: number | undefined,
  benefit: string,
  description: string,
  deadline: string | undefined,
  rules: Rule[],
  extra: string[] = [],
): Scholarship {
  return {
    id,
    title,
    provider,
    mark,
    category,
    amount,
    benefit,
    description,
    deadline,
    rules,
    documents: [...documents, ...extra],
    steps,
    isSample: true,
  };
}
